def write_manifest(path: Path, manifest: SourceManifest) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(manifest.to_dict(), handle, indent=2, ensure_ascii=False)
        handle.write("\n")
    return path


def read_manifest(path: Path) -> SourceManifest:
    return SourceManifest.from_dict(json.loads(Path(path).read_text(encoding="utf-8")))


def render_manifest_markdown(manifest: SourceManifest) -> str:
    """Human-readable source inventory for reports and knowledge pages."""
    lines = [
        f"# Source Manifest — {manifest.state}",
        "",
        f"- Regulator: {manifest.regulator_name or '—'}",
        f"- Regulator URL: {manifest.regulator_url or '—'}",
        f"- Research status: {manifest.research_status or ('researched' if manifest.researched else 'not yet researched')}",
        f"- Updated: {manifest.updated_date or '—'}",
        f"- Sources declared: {len(manifest.sources)}",
        "",
    ]
    if manifest.sources:
        lines += [
            "| Source | Authority | Class | URL | Machine-readable | Format | Discovered | Last checked |",
            "| --- | --- | --- | --- | --- | --- | --- | --- |",
        ]
        def _cell(value: str) -> str:
            return str(value).replace("|", "\\|")

        for source in sorted(manifest.sources, key=lambda s: (s.source_class, s.name)):
            lines.append(
                f"| {_cell(source.name)} "
                f"| {_cell(source.authority)} "
                f"| {source.source_class} "
                f"| <{source.url}> "
                f"| {'yes' if source.machine_readable else 'no'} "
                f"| {source.format} "
                f"| {source.discovered_date or '—'} "
                f"| {source.last_checked_date or '—'} |"
            )
    return "\n".join(lines) + "\n"


def today_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d")


def build_stub_manifest(state: str, *, regulator_name: str = "") -> SourceManifest:
    """A manifest for a state that has NOT been researched.

    Deliberately carries no sources and no regulator claims beyond a plain
    jurisdiction name; ``researched=False`` blocks it from being treated as
    evidence.
    """
    return SourceManifest(
        state=state,
        regulator_name=regulator_name,
        researched=False,
        research_status="not yet researched — stub only",
        updated_date=today_iso(),
        sources=[],
    )


def validate_manifest_file(path: Path) -> list[str]:
    return read_manifest(path).validate()


